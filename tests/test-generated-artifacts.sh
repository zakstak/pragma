#!/usr/bin/env bash
# Check proposed commits, without relying on worktree contents or a prior HEAD.
set -euo pipefail

PRAGMA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
repo="$scratch/repo with spaces"
git init -q "$repo"
cd "$repo"
git config user.name 'Pragma fixture'
git config user.email pragma-fixture@example.invalid
git config commit.gpgsign false
export PRAGMA_OUTPUT_FORMAT=gpt
unset PRAGMA_HOME

check() {
  bash "$PRAGMA_DIR/lib/generated-artifacts.sh" "$@"
}

pass() {
  if ! check >"$scratch/output" 2>&1; then
    printf 'FAIL: %s\n' "$1"
    cat "$scratch/output"
    exit 1
  fi
  printf 'PASS: %s\n' "$1"
}

reject() {
  local label="$1" expected="$2"
  if check >"$scratch/output" 2>&1; then
    printf 'FAIL: %s unexpectedly succeeded\n' "$label"
    exit 1
  fi
  if ! grep -Fq "$expected" "$scratch/output"; then
    printf 'FAIL: %s lacks diagnostic %s\n' "$label" "$expected"
    cat "$scratch/output"
    exit 1
  fi
  printf 'PASS: %s\n' "$label"
}

stage_file() {
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "${2:-fixture}" >"$1"
  git add -f -- "$1"
}

pass 'empty unborn index is accepted'
stage_file src/main.ts 'export const value = 1;'
stage_file assets/authored.png
stage_file assets/data.json
stage_file bin/authored.sh
stage_file vendor/source.rs
stage_file generated/handwritten.ts
stage_file prek.toml '# Generated by pragma'
stage_file .pragma-hooks/generated-artifacts.sh '#!/usr/bin/env bash'
stage_file kingfisher.yaml '# Generated by pragma'
for lock in package-lock.json npm-shrinkwrap.json yarn.lock pnpm-lock.yaml bun.lock bun.lockb Cargo.lock go.sum go.work.sum uv.lock poetry.lock Pipfile.lock pdm.lock Gemfile.lock composer.lock flake.lock mix.lock packages.lock.json Package.resolved pubspec.lock gradle.lockfile .terraform.lock.hcl; do
  stage_file "$lock" '# Automatically generated file. DO NOT EDIT.'
done
pass 'sources, media, JSON, standard lockfiles, and Pragma configuration are allowed'

for artifact in packages/web/node_modules/lib/index.js packages/api/target/debug/app packages/ui/dist/app.js build/output.txt out/program output/generated.png outputs/generated.webp weights/model.bin coverage/lcov.info htmlcov/index.html .next/cache/item .cache/item .gradle/cache .terraform/providers/plugin .venv/lib/pkg.py .pytest_cache/item __pycache__/app.pyc .svelte-kit/output/server.js zig-out/app models/example.gguf models/example.ggml models/example.safetensors models/example.onnx models/example.tflite models/example.pt models/example.pth models/example.ckpt lib/test.o lib/test.obj lib/test.so.1 lib/test.dll lib/test.wasm bundle.min.js app.js.map project.tsbuildinfo proto/service.pb.go proto/service.pb.cc proto/service.pb.h client.g.dart; do
  stage_file "$artifact"
  reject "recognized artifact: $artifact" 'recognized'
  git rm -qf -- "$artifact"
done

odd_path=$'pkg with spaces/build/output\nsecond line.txt'
stage_file "$odd_path"
printf -v quoted_path '%q' "$odd_path"
quoted_json="${quoted_path//\\/\\\\}"
reject 'spaces and newlines remain one safely quoted diagnostic path' "$quoted_json"
PRAGMA_OUTPUT_FORMAT=human reject 'human diagnostics keep newlines quoted' "$quoted_path"
# The hook reads every path even when its caller supplies an unrelated filename.
if check src/main.ts >"$scratch/output" 2>&1; then
  printf 'FAIL: filename arguments restricted the full-index scan\n'
  exit 1
fi
cp .git/index "$scratch/index-before"
reject 'the check preserves index bytes' 'recognized'
cmp .git/index "$scratch/index-before"
git rm -qf -- "$odd_path"

stage_file models/previously-tracked.gguf
git -c core.hooksPath=/dev/null commit -qm 'fixture with existing artifact'
stage_file src/other.ts 'export const other = 2;'
reject 'unchanged tracked artifacts block unrelated changes' 'previously-tracked.gguf'
mkdir -p nested/directory
(cd nested/directory && reject 'subdirectory invocation scans the entire index' 'previously-tracked.gguf')
git rm -qf models/previously-tracked.gguf
pass 'staged artifact deletion is allowed'
mkdir -p models
printf 'untracked\n' >models/untracked.gguf
pass 'untracked artifacts are outside the proposed commit'

stage_file src/generated.go '// Code generated by fixture. DO NOT EDIT.'
printf 'package authored\n' >src/generated.go
reject 'generated header comes from the staged blob' 'generated-source header'
stage_file src/generated.go 'package authored'
printf '// Code generated by fixture. DO NOT EDIT.\n' >src/generated.go
pass 'unstaged generated header does not affect the check'
for marker in '// @generated' '// <auto-generated>' '# Automatically generated file. DO NOT EDIT.'; do
  stage_file src/header.ts "$marker"
  reject 'conventional generated-source header is recognized' 'generated-source header'
done
git rm -qf src/header.ts
stage_file src/quoted.ts 'const text = "// @generated";'
pass 'strings describing generated markers are ordinary source'

stage_file fixtures/model.gguf
printf 'fixtures/model.gguf -pragma-generated\n' >.gitattributes
reject 'unstaged exceptions cannot allow an artifact' 'model.gguf'
git add .gitattributes
pass 'a staged exact-path exception allows a legitimate fixture'
printf '\n' >.gitattributes
pass 'unstaged removal does not revoke the staged exception'
git add .gitattributes
reject 'staged exception removal takes effect' 'model.gguf'
printf 'fixtures/model.gguf pragma-generated=false\n' >.gitattributes
git add .gitattributes
pass 'explicit false also grants a versioned exception'

stage_file fixtures/second.gguf
printf 'second.gguf -pragma-generated\n' >fixtures/.gitattributes
git add fixtures/.gitattributes
pass 'nested staged attributes apply relative to their directory'
for attribute in pragma-generated linguist-generated linguist-generated=true generated generated=true; do
  printf 'fixtures/model.gguf -pragma-generated\nassets/authored.png %s\n' "$attribute" >.gitattributes
  git add .gitattributes
  reject "explicit generated marker: $attribute" 'marked generated in staged .gitattributes'
done
printf 'fixtures/model.gguf -pragma-generated\nsrc/quoted.ts linguist-generated=true\nsrc/quoted.ts -pragma-generated\n' >.gitattributes
git add .gitattributes
pass 'a Pragma exception overrides other generated markers'

mkdir -p .git/info
printf '* pragma-generated\n' >.git/info/attributes
pass 'local info attributes cannot falsely mark files'
printf '* -pragma-generated\n' >.git/info/attributes
stage_file models/blocked.gguf
reject 'local info attributes cannot bypass policy' 'blocked.gguf'
git rm -qf models/blocked.gguf
printf '* pragma-generated\n' >"$scratch/global-attributes"
git config core.attributesFile "$scratch/global-attributes"
pass 'global or repository-local attribute configuration is ignored'
printf '* -pragma-generated\n' >"$scratch/global-attributes"
stage_file models/blocked.gguf
reject 'external attributes cannot bypass policy' 'blocked.gguf'
git rm -qf models/blocked.gguf
rm .git/info/attributes
git config --unset core.attributesFile

stage_file src/marked.ts '// @generated'
printf 'fixtures/model.gguf -pragma-generated\nsrc/marked.ts -pragma-generated\n' >.gitattributes
git add .gitattributes
pass 'a narrow exception allows a generated-code fixture'
printf 'fixtures/model.gguf -pragma-generated\nyarn.lock pragma-generated\nsrc/marked.ts -pragma-generated\n' >.gitattributes
git add .gitattributes
reject 'explicit markers take precedence over lockfile allowance' 'yarn.lock'
printf 'fixtures/model.gguf -pragma-generated\nsrc/marked.ts -pragma-generated\n' >.gitattributes
git add .gitattributes

# The hook must use the alternate index Git hands to it, including staged attrs.
cp .git/index "$scratch/alternate-index"
GIT_INDEX_FILE="$scratch/alternate-index" git update-index --force-remove fixtures/model.gguf fixtures/second.gguf src/marked.ts
printf 'alternate\n' >models/alternate.gguf
GIT_INDEX_FILE="$scratch/alternate-index" git add models/alternate.gguf
if GIT_INDEX_FILE="$scratch/alternate-index" check >"$scratch/output" 2>&1; then
  printf 'FAIL: alternate index was ignored\n'
  exit 1
fi
grep -Fq alternate.gguf "$scratch/output"
pass 'alternate-index checks leave the normal index intact'

git update-index --split-index
pass 'split indexes are supported'
git update-index --no-split-index
cp .git/index "$scratch/index-before"
GIT_DIR="$repo/.git" GIT_COMMON_DIR="$repo/.git" GIT_WORK_TREE="$repo" GIT_INDEX_FILE="$repo/.git/index" pass 'Git hook environment is isolated from temporary attribute evaluation'
cmp .git/index "$scratch/index-before"

# Symlinks are evaluated as index entries, never followed into the worktree.
ln -s "$repo/src/marked.ts" src/link.ts
git add src/link.ts
pass 'symlinks do not cause source-content reads'
git -c core.hooksPath=/dev/null commit -qm 'accepted fixtures'
linked="$scratch/linked worktree"
git worktree add -q --detach "$linked" HEAD
(cd "$linked" && pass 'linked worktree resolves the common object database')

# No Node or language tool is needed in an ordinary unclaimed repository.
minimal_bin="$scratch/minimal-bin"
mkdir "$minimal_bin"
for tool in bash git dirname mktemp mkdir rm head grep; do
  ln -s "$(command -v "$tool")" "$minimal_bin/$tool"
done
PATH="$minimal_bin" PRAGMA_SKIP_INTERNAL_BIN_PATH=1 pass 'the checker needs only Bash, Git, and base system utilities'

sha256_repo="$scratch/sha256"
git init -q --object-format=sha256 "$sha256_repo"
(
  cd "$sha256_repo"
  stage_file src/main.rs 'fn main() {}'
  pass 'SHA-256 repositories preserve their object format'
  stage_file models/test.gguf
  reject 'SHA-256 repositories still reject artifacts' 'test.gguf'
)
